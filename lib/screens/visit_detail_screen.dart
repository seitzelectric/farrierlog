  Future<void> _generateInvoice() async {
    final l10n = AppLocalizations.of(context)!;
    if (_invoices.isNotEmpty) {
      // Show View / Regenerate options
      if (!mounted) return;
      await showModalBottomSheet(
        context: context,
        builder: (ctx) => SafeArea(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              ListTile(
                leading: const Icon(Icons.visibility),
                title: Text(l10n.viewShareInvoiceTitle),
                onTap: () {
                  Navigator.pop(ctx);
                  _viewInvoice(_invoices.first);
                },
              ),
              ListTile(
                leading: const Icon(Icons.refresh, color: Colors.orange),
                title: Text(l10n.regenerateInvoiceTitle,
                    style: const TextStyle(color: Colors.orange)),
                subtitle: Text(l10n.regenerateInvoiceSubtitle),
                onTap: () async {
                  Navigator.pop(ctx);
                  await _confirmRegenerateInvoice();
                },
              ),
            ],
          ),
        ),
      );
      return;
    }

    final client = _client ?? await DatabaseService.getClient(_visit.clientId);
    if (client == null) return;

    try {
      final issuedAt = DateTime.now();
      final invoiceNumber =
          await DatabaseService.getNextInvoiceNumber(issuedAt);
      final file = await InvoiceService.generateInvoice(
        visit: _visit,
        client: client,
        serviceLines: _serviceLines,
        charges: _charges,
        photos: _photos,
        invoiceNumber: invoiceNumber,
      );

      final invoice = InvoiceRecord(
        visitId: _visit.id!,
        invoiceNumber: invoiceNumber,
        issuedAt: issuedAt,
        paidAt: _visit.paid ? issuedAt : null,
        total: _total,
        filePath: file.path,
        fileName: file.path.split('/').last,
      );
      final invoiceId = await DatabaseService.insertInvoice(invoice);

      if (!mounted) return;
      setState(
        () => _invoices = [
          InvoiceRecord(
            id: invoiceId,
            visitId: invoice.visitId,
            invoiceNumber: invoice.invoiceNumber,
            issuedAt: invoice.issuedAt,
            paidAt: invoice.paidAt,
            total: invoice.total,
            filePath: invoice.filePath,
            fileName: invoice.fileName,
            createdAt: invoice.createdAt,
            updatedAt: invoice.updatedAt,
          ),
        ],
      );

      final last = client.lastName.trim().replaceAll(RegExp(r'[^a-zA-Z0-9]+'), '_');
      final first = client.firstName.trim().replaceAll(RegExp(r'[^a-zA-Z0-9]+'), '_');
      final namePart = first.isNotEmpty ? '${last}_$first' : last;
      final dateStr = _visit.dateTime.toIso8601String().split('T').first;
      final shareFileName = '${namePart}_$dateStr.pdf';

      final hasInvoicePhotos = _photos.any((p) => p.includeOnInvoice);
      showModalBottomSheet(
        context: context,
        builder: (bsCtx) => SafeArea(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              if (hasInvoicePhotos) ...[
                ListTile(
                  leading: const Icon(Icons.receipt_long),
                  title: Text(l10n.shareInvoiceOnlyTitle),
                  subtitle: Text(l10n.shareInvoiceOnlySubtitle),
                  onTap: () async {
                    Navigator.pop(bsCtx);
                    try {
                      final invoiceOnlyFile =
                          await InvoiceService.generateInvoice(
                        visit: _visit,
                        client: client,
                        serviceLines: _serviceLines,
                        charges: _charges,
                        photos: _photos,
                        invoiceNumber: invoiceNumber,
                        includePhotos: false,
                      );
                      await InvoiceService.shareInvoice(
                        invoiceOnlyFile,
                        subject: l10n.invoiceSubjectFor(client.fullName),
                        fileName: shareFileName,
                      );
                    } catch (e) {
                      if (!mounted) return;
                      ScaffoldMessenger.of(context).showSnackBar(
                        SnackBar(content: Text(l10n.errorSharingInvoiceSnackbar('$e'))),
                      );
                    }
                  },
                ),
                ListTile(
                  leading: const Icon(Icons.photo_library),
                  title: Text(l10n.shareInvoicePhotosTitle),
                  subtitle: Text(l10n.shareInvoicePhotosSubtitle),
                  onTap: () {
                    Navigator.pop(bsCtx);
                    InvoiceService.shareInvoice(
                      file,
                      subject: l10n.invoiceSubjectFor(client.fullName),
                      fileName: shareFileName,
                    );
                  },
                ),
              ] else
                ListTile(
                  leading: const Icon(Icons.share),
                  title: Text(l10n.shareInvoicePdfTitle),
                  subtitle: Text(l10n.shareInvoicePdfSubtitle),
                  onTap: () {
                    Navigator.pop(bsCtx);
                    InvoiceService.shareInvoice(
                      file,
                      subject: l10n.invoiceSubjectFor(client.fullName),
                      fileName: shareFileName,
                    );
                  },
                ),
              ListTile(
                leading: const Icon(Icons.print),
                title: Text(l10n.printInvoiceTitle),
                onTap: () {
                  Navigator.pop(bsCtx);
                  InvoiceService.printInvoice(file);
                },
              ),
            ],
          ),
        ),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(l10n.errorGeneratingInvoiceSnackbar('$e'))),
      );
    }
  }

  Future<void> _confirmRegenerateInvoice() async {
    if (_invoices.isEmpty) return;
    final l10n = AppLocalizations.of(context)!;
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text(l10n.regenerateInvoiceConfirmTitle),
        content: Text(l10n.regenerateInvoiceConfirmMessage),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            child: Text(l10n.cancel),
          ),
          ElevatedButton(
            style: ElevatedButton.styleFrom(
                backgroundColor: Colors.orange,
                foregroundColor: Colors.white),
            onPressed: () => Navigator.pop(ctx, true),
            child: Text(l10n.regenerateButton),
          ),
        ],
      ),
    );
    if (confirmed != true) return;

    final invoice = _invoices.first;
    final f = File(invoice.filePath);
    if (await f.exists()) await f.delete();
    await DatabaseService.deleteInvoice(invoice.id!);
    setState(() => _invoices = []);
    await _generateInvoice();
  }

  Future<File?> _ensureInvoiceFile(InvoiceRecord invoice) async {
    if (invoice.filePath.isNotEmpty) {
      final existing = File(invoice.filePath);
      if (await existing.exists()) return existing;
    }

    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            AppLocalizations.of(context)!.invoicePdfNotFoundSnackbar(
              invoice.fileName.isEmpty ? invoice.invoiceNumber : invoice.fileName,
            ),
          ),
        ),
      );
    }
    return null;
  }

  Future<void> _viewInvoice(InvoiceRecord invoice) async {
    final file = await _ensureInvoiceFile(invoice);
    if (!mounted || file == null) return;

    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => Scaffold(
          appBar: AppBar(title: Text(invoice.invoiceNumber)),
          body: PdfPreview(
            canChangePageFormat: false,
            canChangeOrientation: false,
            canDebug: false,
            build: (_) => file.readAsBytes(),
          ),
        ),
      ),
    );
  }

