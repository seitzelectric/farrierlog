class VisitDetailScreen extends StatefulWidget {
  final Visit visit;
  const VisitDetailScreen({super.key, required this.visit});

  @override
  State<VisitDetailScreen> createState() => _VisitDetailScreenState();
}

class _VisitDetailScreenState extends State<VisitDetailScreen> {
  late Visit _visit;
  Client? _client;
  List<Horse> _horses = [];
  List<ServiceLine> _serviceLines = [];
  List<VisitCharge> _charges = [];
  List<VisitPhoto> _photos = [];
  List<InvoiceRecord> _invoices = [];
  bool _loading = true;

  late TextEditingController _invoiceNotesCtrl;
  Timer? _notesSaveTimer;

  @override
  void initState() {
    super.initState();
    _visit = widget.visit;
    _invoiceNotesCtrl = TextEditingController(text: _visit.notes);
    _loadData();
  }

  @override
  void dispose() {
    _notesSaveTimer?.cancel();
    _invoiceNotesCtrl.dispose();
    super.dispose();
  }

  Future<void> _loadData() async {
    final visit = await DatabaseService.getVisit(_visit.id!);
    final horses = await DatabaseService.getHorsesForVisit(_visit.id!);
    final serviceLines = await DatabaseService.getServiceLines(_visit.id!);
    final charges = await DatabaseService.getVisitCharges(_visit.id!);
    final photos = await DatabaseService.getPhotos(_visit.id!);
    final invoices = await DatabaseService.getInvoicesForVisit(_visit.id!);
    final client = await DatabaseService.getClient(_visit.clientId);
    if (mounted) {
      setState(() {
        if (visit != null) {
          _visit = visit;
          // Sync the text controller if user isn't actively editing
          if (!_invoiceNotesCtrl.text.contains(visit.notes) ||
              _invoiceNotesCtrl.text == _visit.notes) {
            _invoiceNotesCtrl.removeListener(_scheduleNotesSave);
            _invoiceNotesCtrl.text = visit.notes;
            _invoiceNotesCtrl.addListener(_scheduleNotesSave);
          }
        }
        _client = client;
        _horses = horses;
        _serviceLines = serviceLines;
        _charges = charges;
        _photos = photos;
        _invoices = invoices;
        _loading = false;
      });
    }
  }

  void _scheduleNotesSave() {
    _notesSaveTimer?.cancel();
    _notesSaveTimer = Timer(const Duration(milliseconds: 800), () async {
      await DatabaseService.updateVisitNotes(_visit.id!, _invoiceNotesCtrl.text);
      if (mounted) {
        setState(() {
          _visit = _visit.copyWith(notes: _invoiceNotesCtrl.text);
        });
      }
    });
  }

  double get _serviceLinesTotal =>
      _serviceLines.fold(0.0, (sum, line) => sum + line.lineTotal);
  double get _chargesTotal => _charges.fold(0.0, (sum, c) => sum + c.total);
  double get _total => _serviceLinesTotal + _chargesTotal;

  Future<void> _togglePaid(bool value) async {
    final wasPaid = _visit.paid;
    await DatabaseService.setVisitPaid(_visit.id!, value);
    await DatabaseService.setInvoicesPaidForVisit(_visit.id!, value);
    setState(() {
      _visit = _visit.copyWith(paid: value);
    });
    if (!mounted) return;
    if (!wasPaid &&
        value &&
        _visit.recurrenceWeeks != null &&
        _visit.nextRecurringVisitId == null) {
      final l10n = AppLocalizations.of(context)!;
      final scheduleNext = await ConfirmationDialog.show(
        context,
        title: l10n.recurringVisitTitle,
        message: l10n.scheduleNextRecurringVisit,
      );
      if (scheduleNext == true) {
        await DatabaseService.generateRecurringChain(_visit, weeksAhead: 10);
      }
    }
    _loadData();
  }

  Future<void> _toggleCompleted(bool value) async {
    await DatabaseService.setVisitCompleted(_visit.id!, value);
    setState(() {
      _visit = _visit.copyWith(completed: value);
    });
  }

